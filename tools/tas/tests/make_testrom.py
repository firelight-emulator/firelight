#!/usr/bin/env python3
# Build a minimal Game Boy ROM for the TAS determinism gate. All program code is
# ours; the 48-byte boot logo at 0x104..0x133 is the standard Game Boy cartridge
# header constant that every GB ROM must contain to be recognized (mGBA validates
# it on load), included here for that sole purpose. The program is a tiny
# deterministic loop (increment a WRAM byte forever) -- all the gate needs: the
# same inputs must reproduce the same run.
import sys
rom = bytearray(b"\x00" * 0x8000)          # 32 KiB, MBC0 (ROM only)

# entry @0x100: nop ; jp 0x0150
rom[0x100:0x104] = bytes([0x00, 0xC3, 0x50, 0x01])

# Game Boy boot logo @0x104..0x133 (required header constant; checked at load).
rom[0x104:0x134] = bytes([
    0xCE, 0xED, 0x66, 0x66, 0xCC, 0x0D, 0x00, 0x0B, 0x03, 0x73, 0x00, 0x83,
    0x00, 0x0C, 0x00, 0x0D, 0x00, 0x08, 0x11, 0x1F, 0x88, 0x89, 0x00, 0x0E,
    0xDC, 0xCC, 0x6E, 0xE6, 0xDD, 0xDD, 0xD9, 0x99, 0xBB, 0xBB, 0x67, 0x63,
    0x6E, 0x0E, 0xEC, 0xCC, 0xDD, 0xDC, 0x99, 0x9F, 0xBB, 0xB9, 0x33, 0x3E,
])

# header
title = b"FLTMTEST"
rom[0x134:0x134 + len(title)] = title
rom[0x147] = 0x00   # cartridge type: ROM ONLY
rom[0x148] = 0x00   # ROM size: 32 KiB
rom[0x149] = 0x00   # RAM size: none
rom[0x14A] = 0x01   # destination: non-Japan
rom[0x14B] = 0x33   # old licensee (use new-licensee area)
rom[0x14C] = 0x00   # mask ROM version

# program @0x150:  loop { a = [C000]; a++; [C000] = a }  -> deterministic forever
rom[0x150:0x15A] = bytes([
    0xFA, 0x00, 0xC0,   # ld a, (0xC000)
    0x3C,               # inc a
    0xEA, 0x00, 0xC0,   # ld (0xC000), a
    0xC3, 0x50, 0x01,   # jp 0x0150
])

# header checksum @0x14D over 0x134..0x14C
x = 0
for i in range(0x134, 0x14D):
    x = (x - rom[i] - 1) & 0xFF
rom[0x14D] = x
# global checksum @0x14E..0x14F (big-endian sum of all bytes except these two)
s = (sum(rom) - rom[0x14E] - rom[0x14F]) & 0xFFFF
rom[0x14E], rom[0x14F] = (s >> 8) & 0xFF, s & 0xFF

open(sys.argv[1] if len(sys.argv) > 1 else "testrom.gb", "wb").write(rom)
print("wrote", sys.argv[1], len(rom), "bytes  header_cksum=0x%02X" % rom[0x14D])
