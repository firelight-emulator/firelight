#pragma once

#include <firelight/library/content_file.hpp>

#include <optional>
#include <string>
#include <vector>

namespace firelight::library {

/**
 * Where a set's playlist is written
 */
enum class PlaylistLocation {
  // Beside the discs, so the set is one game in other frontends too
  BesideDiscs,
  // In the app's own directory, so a read-only or archival games folder is never written to
  AppData,
};

/**
 * A playlist ready to be written
 */
struct PlaylistPlan {
  std::string path;
  std::string contents;
  // Whether every line is relative. An absolute playlist stops working the moment the games
  // folder moves, which is worth telling somebody about rather than letting them find out
  bool isPortable = false;
};

/**
 * Works out the playlist for a set's discs, or nothing when there is no useful one to write.
 *
 * Lines are ordered by disc number, which is what makes the same discs give the same playlist
 * however they were found. That matters more than it looks: the identity of a playlist is read
 * from its first line, so an order that followed the scan would move the whole set's identity
 *
 * @param setId Separates one set's playlist from another's when they share a title
 */
[[nodiscard]] std::optional<PlaylistPlan> planPlaylist(const std::vector<ContentFile> &discs, int setId,
                                                       const std::string &title, PlaylistLocation location,
                                                       const std::string &appDataDirectory);

/**
 * Strips the characters a filename cannot hold, along with the trailing dots and spaces
 * Windows drops silently
 */
[[nodiscard]] std::string sanitizeFileName(const std::string &name);

/**
 * The comment a generated playlist opens with. Other frontends skip comment lines, and it is
 * what tells a playlist we wrote from one somebody made themselves after the library database
 * has been thrown away
 */
inline constexpr auto PLAYLIST_MARKER = "# Generated by Firelight";

/**
 * Whether a playlist on disk is one of ours
 */
[[nodiscard]] bool isGeneratedPlaylist(const std::string &contents);

} // namespace firelight::library
