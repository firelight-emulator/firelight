#pragma once

#include <firelight/library/content_file.hpp>

#include <optional>
#include <string>
#include <vector>

namespace firelight::library {

/**
 * A playlist ready to be written
 */
struct PlaylistPlan {
  std::string path;
  std::string contents;
};

/**
 * Where a set's playlist goes.
 *
 * A pure function of the identity, so nothing has to remember it and it is the same path on
 * every run. The name is the hash rather than the title because a core that manages its own
 * memory card names it after the file it was handed, and a retitled set must not come back to
 * a blank card
 */
[[nodiscard]] std::string playlistPathFor(const std::string &contentHash, const std::string &appDataDirectory);

/**
 * Works out the playlist for a set's discs, or nothing when there is no useful one to write.
 *
 * Lines are ordered by disc number, which is what makes the same discs give the same playlist
 * however they were found. That matters more than it looks: the identity of a playlist is read
 * from its first line, so an order that followed the scan would move the whole set's identity
 *
 * @param contentHash What the set launches under, which also names the file
 */
[[nodiscard]] std::optional<PlaylistPlan> planPlaylist(const std::vector<ContentFile> &discs,
                                                       const std::string &contentHash,
                                                       const std::string &appDataDirectory);

/**
 * The comment playlists written by older versions open with, which is what tells one we wrote
 * from one somebody made themselves
 */
inline constexpr auto PLAYLIST_MARKER = "# Generated by Firelight";

/**
 * Whether a playlist on disk is one of ours
 */
[[nodiscard]] bool isGeneratedPlaylist(const std::string &contents);

} // namespace firelight::library
