#pragma once

#include <firelight/library/metadata_overrides.hpp>
#include <firelight/util/game_metadata.hpp>

#include <cstdint>
#include <optional>
#include <string>
#include <vector>

namespace firelight::library {
struct Entry {
  int id = -1;
  std::string displayName;
  bool nameUserSet = false; // So we don't overwrite a user-edited name with metadata
  std::string contentHash;
  unsigned platformId = 0;
  unsigned activeSaveSlot = 1;
  bool hidden = false; // Hidden manually by the user

  bool isContentAvailable = false; // Whether any copy of this content is still on disk
  bool hasRunConfiguration = false;

  bool isDiscInArchive = false;
  bool favorite = false;
  unsigned rating = 0; // 0-5, 0 when not rated
  std::string icon1x1SourceUrl;
  std::string boxartFrontSourceUrl;
  std::string boxartBackSourceUrl;

  GameMetadata metadata{};               // The metadata generated by scrapers and set by the user
  MetadataOverrides metadataOverrides{}; // The metadata fields the user has overridden (scrapes skip them)

  std::string normalizedTitle;

  std::optional<int> discSetId{}; // The multi-disc game this entry is, when it is one

  std::optional<int> variantGroupId{}; // The set of variant groups this entry is one of
  bool variantGroupUserSet = false;    // Whether a person decided this entry's membership so it's not overridden

  std::optional<uint64_t> artFetchedAt{}; // Empty means never attempted

  std::vector<int> folderIds{};
  std::vector<int> tagIds{};

  std::vector<int> contentDirectoryIds{};
  std::vector<std::string> contentPaths{};
  std::vector<std::string> readableContentPaths{}; // The subset of contentPaths whose file has not been marked missing

  int position = 0; // Position in global sort (not in collection)

  uint64_t createdAt = 0;
};
} // namespace firelight::library
